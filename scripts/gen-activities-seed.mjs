// Generates supabase/migrations/20261010000003_seed_activities.sql from the app's own catalogue,
// so the server-side activity list always matches what the app can record.
// Usage: node scripts/gen-activities-seed.mjs  (re-run whenever games/maps/books/pensel change)
import { writeFileSync } from "node:fs";
import { buildCatalog } from "./activity-catalog.mjs";

const rows = await buildCatalog();
const q = (s) => (s == null ? "null" : `'${String(s).replace(/'/g, "''")}'`);
const arr = (a) => (a ? `array[${a.map(q).join(", ")}]::text[]` : "null");
const values = rows.map((r) => `  (${q(r.id)}, ${q(r.category)}, ${q(r.title)}, ${q(r.kind)}, ${r.question_count ?? "null"}, ${arr(r.items)}, ${q(r.item_pattern)}, ${r.sort_order})`).join(",\n");
const sql = `-- Playora — 0003 activity catalogue seed (GENERATED by scripts/gen-activities-seed.mjs — do not edit by hand)
-- Upsert: new activities are added; structure (kind, counts, items) is refreshed;
-- an admin's publish/unpublish choice and title edits are preserved.
insert into public.activities (id, category, title, kind, question_count, items, item_pattern, sort_order) values
${values}
on conflict (id) do update set
  category = excluded.category, kind = excluded.kind, question_count = excluded.question_count,
  items = excluded.items, item_pattern = excluded.item_pattern;
`;
writeFileSync(new URL("../supabase/migrations/20261010000003_seed_activities.sql", import.meta.url), sql);
console.log(`wrote ${rows.length} activities`);
