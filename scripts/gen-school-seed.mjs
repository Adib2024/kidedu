// Generates a migration that brings the server's Sekolah activity catalogue in line with js/school/curriculum.js,
// so every chapter the app can record is accepted by record_attempt.
// Usage: node scripts/gen-school-seed.mjs <migration-file-name>
//   e.g. node scripts/gen-school-seed.mjs 20261027000008_sekolah_sains.sql
// Always write a NEW file when topics change — never regenerate a migration that is already applied
// (20261026000007_sekolah.sql also created the 'sekolah' category and children.grade).
import { writeFileSync, existsSync } from "node:fs";
import { buildSchoolCatalog } from "./activity-catalog.mjs";

const name = process.argv[2];
if (!name || !/^\d{14}_[a-z0-9_]+\.sql$/.test(name)) { console.error("usage: node scripts/gen-school-seed.mjs <YYYYMMDDhhmmss_name.sql>"); process.exit(1); }
const out = new URL(`../supabase/migrations/${name}`, import.meta.url);
if (existsSync(out)) { console.error(`${name} already exists — choose a new file name`); process.exit(1); }

const rows = await buildSchoolCatalog();
const q = (s) => (s == null ? "null" : `'${String(s).replace(/'/g, "''")}'`);
const arr = (a) => (a ? `array[${a.map(q).join(", ")}]::text[]` : "null");
const values = rows.map((r) => `  (${q(r.id)}, ${q(r.category)}, ${q(r.title)}, ${q(r.kind)}, ${r.question_count ?? "null"}, ${arr(r.items)}, ${q(r.item_pattern)}, ${r.sort_order})`).join(",\n");
const sql = `-- Playora: Sekolah chapter catalogue refresh (new subjects / chapters).
-- GENERATED by scripts/gen-school-seed.mjs. Idempotent and additive: no rows are removed and existing
-- chapter ids are kept, so recorded progress stays valid. Requires 20261026000007_sekolah.sql.
insert into public.activities (id, category, title, kind, question_count, items, item_pattern, sort_order) values
${values}
on conflict (id) do update set
  category = excluded.category, kind = excluded.kind, question_count = excluded.question_count,
  items = excluded.items, item_pattern = excluded.item_pattern;
`;
writeFileSync(out, sql);
console.log(`wrote ${name}: ${rows.length} school activity families`);
