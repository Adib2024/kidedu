// Generates supabase/migrations/20261026000007_sekolah.sql from js/school/curriculum.js so the server's
// activity catalogue always matches the chapters the app can record.
// Usage: node scripts/gen-school-seed.mjs   (re-run when Sekolah topics change; then add a NEW migration
// with the output instead of editing an applied one)
import { writeFileSync } from "node:fs";
import { buildSchoolCatalog } from "./activity-catalog.mjs";

const rows = await buildSchoolCatalog();
const q = (s) => (s == null ? "null" : `'${String(s).replace(/'/g, "''")}'`);
const arr = (a) => (a ? `array[${a.map(q).join(", ")}]::text[]` : "null");
const values = rows.map((r) => `  (${q(r.id)}, ${q(r.category)}, ${q(r.title)}, ${q(r.kind)}, ${r.question_count ?? "null"}, ${arr(r.items)}, ${q(r.item_pattern)}, ${r.sort_order})`).join(",\n");
const sql = `-- Playora 0007: Sekolah (Darjah 1-6) - new activity category, chapter catalogue, child school year.
-- GENERATED by scripts/gen-school-seed.mjs. Idempotent and additive: no rows are removed.

-- 1. allow the 'sekolah' category (the check constraint is only replaced while it lacks 'sekolah')
do $mig$
begin
  if exists (select 1 from pg_constraint where conrelid = 'public.activities'::regclass and conname = 'activities_category_check'
             and pg_get_constraintdef(oid) not like '%sekolah%') then
    alter table public.activities drop constraint activities_category_check;
  end if;
  if not exists (select 1 from pg_constraint where conrelid = 'public.activities'::regclass and conname = 'activities_category_check') then
    alter table public.activities add constraint activities_category_check
      check (category in ('games', 'peta', 'buku', 'pensel', 'rutin', 'sekolah'));
  end if;
end $mig$;

-- 2. school year per child (0 = Prasekolah, 1-6 = Tahun 1-6; null = derive from age)
alter table public.children add column if not exists grade smallint;
do $mig$
begin
  if not exists (select 1 from pg_constraint where conname = 'children_grade_range') then
    alter table public.children add constraint children_grade_range check (grade between 0 and 6);
  end if;
end $mig$;

-- 3. chapter catalogue: one family per subject and year; item = "<topic>-<latihan|masa|bos>"
insert into public.activities (id, category, title, kind, question_count, items, item_pattern, sort_order) values
${values}
on conflict (id) do update set
  category = excluded.category, kind = excluded.kind, question_count = excluded.question_count,
  items = excluded.items, item_pattern = excluded.item_pattern;
`;
writeFileSync(new URL("../supabase/migrations/20261026000007_sekolah.sql", import.meta.url), sql);
console.log(`wrote ${rows.length} school activity families`);
